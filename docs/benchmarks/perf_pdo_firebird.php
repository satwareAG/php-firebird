<?php
// satware-docs/benchmarks/perf_pdo_firebird.php
// Benchmark basic operations using the PDO_Firebird driver.
//
// Usage:
//   php satware-docs/benchmarks/perf_pdo_firebird.php
//
// Make sure:
//   - The `pdo_firebird` extension is enabled (php -m | grep PDO_Firebird)
//   - PDO reports the `firebird` driver (check PDO::getAvailableDrivers())
//   - satware-docs/benchmarks/config.php is filled with a working DSN and credentials
//   - The Firebird database contains a table `perf_test(id INTEGER, payload VARCHAR(100))`
//
// Example table:
//   CREATE TABLE perf_test (
//     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
//     payload VARCHAR(100)
//   );
//   INSERT INTO perf_test(payload) VALUES ('test row');
//   COMMIT;

if (!extension_loaded('PDO_Firebird') && !in_array('firebird', PDO::getAvailableDrivers(), true)) {
    fwrite(STDERR, "PDO_Firebird is not available (extension or driver missing).\n");
    exit(1);
}

$config = require __DIR__ . '/config.php';

$iterations = 1000;

function bench(string $label, callable $fn, int $iterations): void
{
    $start = hrtime(true);
    for ($i = 0; $i < $iterations; $i++) {
        $fn();
    }
    $elapsedNs = hrtime(true) - $start;
    $elapsedMs = $elapsedNs / 1_000_000;
    printf("%-36s %10.2f ms (%d iterations)\n", $label . ':', $elapsedMs, $iterations);
}

// 1) Connect + simple SELECT per iteration
bench('PDO connect+select', function () use ($config): void {
    try {
        $pdo = new PDO(
            $config['dsn'],
            $config['user'],
            $config['password'],
            [
                PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_NUM,
            ]
        );
        $stmt = $pdo->query('SELECT 1 FROM RDB$DATABASE');
        if ($stmt !== false) {
            $stmt->fetch();
        }
    } catch (Throwable $e) {
        // Error already printed to STDERR; keep benchmark loop running.
    }
}, $iterations);

// 2) Reuse a single connection for all iterations
try {
    $pdo = new PDO(
        $config['dsn'],
        $config['user'],
        $config['password'],
        [
            PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_NUM,
        ]
    );
} catch (Throwable $e) {
    fwrite(STDERR, "Failed to connect via PDO for reuse benchmark: " . $e->getMessage() . "\n");
    exit(1);
}

bench('PDO reused connect+select', function () use ($pdo): void {
    try {
        $stmt = $pdo->query('SELECT 1 FROM RDB$DATABASE');
        if ($stmt !== false) {
            $stmt->fetch();
        }
    } catch (Throwable $e) {
        // Ignore individual iteration failures for timing purposes.
    }
}, $iterations);

// 3) Prepared statement with positional parameter against perf_test
try {
    $stmt = $pdo->prepare('SELECT payload FROM perf_test WHERE id = ?');
    if ($stmt === false) {
        fwrite(STDERR, "Failed to prepare statement on perf_test.\n");
        exit(1);
    }
} catch (Throwable $e) {
    fwrite(STDERR, "Failed to prepare statement on perf_test: " . $e->getMessage() . "\n");
    exit(1);
}

bench('PDO prepared select with param', function () use ($stmt): void {
    try {
        if ($stmt->execute([1])) {
            $stmt->fetch();
        }
    } catch (Throwable $e) {
        // Ignore individual iteration failures for timing purposes.
    }
}, $iterations);
